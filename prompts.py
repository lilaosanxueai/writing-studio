def titles_prompt() -> str:
    """标题工坊：一稿十题，覆盖不同手法"""
    return (
        "你是标题工坊。基于成稿内容生成 10 个标题，手法必须覆盖：数字式、反差式、"
        "提问式、悬念式、引用金句式、身份代入式、对话式、画面式等，不重复。"
        "只输出一个 JSON 对象（共 10 个元素），不要任何解释、不要 markdown 代码块：\n"
        '{"titles": [{"text": "标题内容", "type": "手法名"}, {"text": "标题内容", "type": "手法名"}]}\n\n'
        "要求：每个标题≤16 字；贴合正文内容，禁止正文兑现不了的标题党；"
        "允许其中最多两个适度冒险的，其余求稳。只基于稿子本身。\n\n"
        "成稿内容：\n"
    )


def convert_prompt(src_label: str, dst_label: str) -> str:
    """一稿多发：把已成稿改写成另一种格式"""
    return (
        f"你是改写手。手上有用户已完成的「{src_label}」成稿（它本身基于真实讨论材料）。"
        f"任务：把它改写成「{dst_label}」版本。\n\n"
        "铁律：\n"
        "- 忠于原稿：观点、事实、金句一律沿用原稿，不新增原稿与讨论里没有的内容。\n"
        "- 按目标格式的结构与节奏彻底重写，不是裁剪粘贴；语气可随平台微调，人设不变。\n"
        "- 原稿的标题可弃可改。\n"
        "- 只输出改写后的成稿本身，不要解释。\n"
    )


def weekly_report_prompt(stats_text: str) -> str:
    """写作周报：数据 + 亮点 + 教练点评 + 下周建议"""
    return (
        "你是写作教练。根据这位写作者本周的写作数据与产出，写一份周报。"
        "直接输出 markdown（用 ## 小节），不要开场白：\n"
        "## 本周数据\n把下面的原始数据重新组织成人话，加一两句解读（不要罗列全部数字）。\n"
        "## 本周亮点\n挑出真正值得说的亮点（好句子、好习惯、突破），引用原文金句。\n"
        "## 教练说\n一两句话，要么犀利要么温暖，看数据说话；数据少就鼓励，数据好就提要求。\n"
        "## 下周建议\n2~3 条具体的、可执行的建议（结合他的分类与画像）。\n\n"
        f"本周原始数据：\n{stats_text}\n"
    )


def import_prompt() -> str:
    """素材导入：粘贴的长文 → 金句灵感 + 话题方向"""
    return (
        "你是写作素材整理员。用户粘贴了一段现成的文字（可能是笔记、文章、聊天记录、"
        "读书摘抄）。从中提炼出可以用于后续写作的材料。只输出一个 JSON 对象，"
        "不要任何解释：\n"
        '{"gist": "一句话概括这段材料在说什么（30字内）", '
        '"sparks": ["值得收藏的金句或观点，保持原文措辞", …5~10条], '
        '"topics": [{"title": "从材料里长出来的话题方向，12字内", '
        '"hook": "搭档的开场白，60字内，直接抛切入问题"}]（3个，角度彼此不同）}\n\n'
        "要求：sparks 优先原文里的好句子（保留原措辞，可轻度修剪），"
        "材料太薄时可以少于 5 条但不少于 3 条；topics 要能和写作者自身经验接上，"
        "不是复述材料内容。\n\n"
        "材料原文：\n"
    )


def forge_quotes_prompt() -> str:
    """金句锻造坊：从话题材料批量锻造金句"""
    return (
        "你是金句锻造师。根据下面的讨论记录与灵感卡片，锻造 8~10 条全新的金句"
        "（不是搬运原文已有的，是从材料里长出来的新表达）。"
        "只输出一个 JSON 对象，不要任何解释：\n"
        '{"quotes": [{"text": "金句", "technique": "手法"}, …共8~10条]}\n\n'
        "手法限定：对仗、反差、具象换抽象、时间对照、大小对照、口语断言。每条≤30字。\n"
        "严禁格言腔与心灵鸡汤腔；要像一个人说话说到兴头上的那句，不像墙上标语。\n"
        "每条必须能从材料里找到根，不发明材料外的观点。\n\n"
    )


def style_learn_prompt() -> str:
    """文风采集：从作者过去的文字蒸馏专属文风卡"""
    return (
        "你是文风分析师。下面是一位写作者过去的文字样本。从中蒸馏出他的文风卡，"
        "输出为可直接用作写作指令的要点列表（150 字以内），涵盖：\n"
        "- 句子长度与节奏习惯（长句为主还是短句为主？长短如何交错？）\n"
        "- 标点与语气词习惯（逗号密度、问句多少、语气词用不用）\n"
        "- 词汇偏好（书面还是口语？爱用什么类型的词？避讳什么？）\n"
        "- 结构习惯（怎么开头？怎么收尾？段落长短？）\n"
        "- 情绪表达方式（直给还是克制？幽默感是什么类型的？）\n"
        "- 金句手法（如果样本里有金句，它靠什么成立？）\n\n"
        "只描述样本里有证据的特征，宁缺毋滥；不评价好坏。"
        "直接输出要点列表，不要开场白。\n\n"
        "文字样本：\n"
    )


