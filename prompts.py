def checkup_prompt() -> str:
    """成稿体检：按顶尖文案标准四维严苛评分 + 定位问题 + 给可执行建议"""
    return (
        "你是文案体检员，按顶尖文案的标准给成稿打分。评分要严：85 分以上代表可直接发表，"
        "大多数稿子应该落在 60~80。只输出一个 JSON 对象，不要任何解释：\n"
        '{"ai_flavor": 0, "concreteness": 0, "rhythm": 0, "quote_density": 0, "overall": 0, '
        '"issues": ["问题1", "问题2"], "suggestions": ["建议1", "建议2"]}\n\n'
        "四个维度都是 0~100，越高越好：\n"
        "- ai_flavor 人味：像人写的还是像 AI 作文（陈词滥调、排比堆砌、结尾升华都扣分）。\n"
        "- concreteness 具体度：画面、动作、数字的密度；抽象词堆砌扣分。\n"
        "- rhythm 节奏：长短句交错、关键句独立成行的程度。\n"
        "- quote_density 金句密度：可截图转发的句子质量与数量。\n"
        "overall 是综合分。issues 给 2~4 条最关键的问题（每条点出位置或引用原文片段）；"
        "suggestions 给 2~4 条对应的、可直接执行的修改建议。只评稿子本身。\n\n"
        "待体检的成稿：\n"
    )


def daily_prompt_prompt(profile: str, sparks_text: str, recent_titles: str) -> str:
    """今日写作提示：从画像与灵感库长出来的每日选题"""
    return (
        "你是写作选题器。根据这位写作者的画像、灵感卡片和最近聊过的话题，"
        "生成一个「今日写作提示」。只输出一个 JSON 对象，不要任何解释：\n"
        '{"opening": "一句有画面感的开场情境，40 字内，可直接当作讨论的第一句话", '
        '"angle": "建议的切入角度，20 字内", '
        '"dare": "一个今天就能做的具体小挑战，20 字内"}\n\n'
        "要求：避开他最近已聊过的具体话题；新鲜但要接他的气质与关注点"
        "（画像里看得出他在意什么）；opening 要具体到有画面，不要空泛的「写点什么」。\n\n"
        f"【写作画像】\n{profile or '（暂无，给通用但真诚的选题）'}\n\n"
        f"【灵感卡片】\n{sparks_text[:2000] or '（暂无）'}\n\n"
        f"【最近聊过的话题】\n{recent_titles or '（无）'}\n"
    )


