def draft_system_prompt(fmt_label: str, tone: str, length: str, extra: str,
                        profile: str = "", fmt_key: str = "",
                        style: str = "none", style_custom: str = "") -> str:
    profile_note = f"\n作者偏好（贴合他的表达习惯，他自己的用词优先）：{profile}\n" if profile else ""
    playbook = GENRE_PLAYBOOKS.get(fmt_key, f"按「{fmt_label}」的惯常结构组织。")
    style_note = ""
    if style in STYLE_CARDS:
        style_note = f"\n{STYLE_CARDS[style]}\n"
    elif style == "custom" and style_custom.strip():
        style_note = f"\n【风格卡：自定义】模仿这个风格描述（学其手法与语感，不抄其原句）：{style_custom.strip()[:300]}\n"
    return (
        "你是顶尖文案写手，同时是材料的整理者。手上有用户和写作搭档的完整讨论记录、"
        f"以及讨论中收集的灵感卡片。任务：把这些真实材料整理成一篇「{fmt_label}」。\n\n"
        "材料铁律：\n"
        "- 优先用用户自己说过的话、举过的例子、冒出来的金句；"
        "讨论里没有的观点不要发明，缺素材的地方宁可留白也不要编。\n"
        "- 具体画面优先从讨论材料里提取；需要推演细节时只能用无特异性的通用场景"
        "（如「睡前刷手机」），严禁虚构作者没提过的具体事实（家庭成员、职业、地点等）。\n"
        "- 成稿里不出现「我们聊到」「你说过」这类对话痕迹，直接以成品口吻写。\n\n"
        f"{CRAFT_RULES}\n{playbook}{style_note}\n"
        f"语气：{tone}\n长度：{length}\n{profile_note}"
        + (f"用户附加要求：{extra}\n" if extra else "")
        + "\n只输出成稿本身（可带标题），不要解释你做了什么。"
    )


def polish_prompt() -> str:
    """打磨：编辑红笔二遍稿，把「通顺」提到「发表级」"""
    return (
        "你是一位顶尖文案编辑，负责把成稿从「通顺」打磨到「发表级」。"
        "手上有原稿和它的讨论材料。用红笔逐段过一遍，专砍这些毛病：\n"
        "1. AI 味：陈词滥调（「在这个…的时代」「毋庸置疑」、排比堆砌、结尾升华总结）。\n"
        "2. 抽象无画面：「厚度」「温度」「力量」这类没画面的词，"
        "换成材料里或合理推演出的具体场景、动作、细节。\n"
        "3. 节奏均匀：连续等长句拆成长短交错；关键句独占一行。\n"
        "4. 虚词软弱：删掉假谦虚的「可能/也许/大概」。\n"
        "5. 金句锻造：从材料里再锻出至少一句新的可引用句（对仗、反差或具象，不要格言腔）。\n"
        "6. 结尾：若是总结升华，改成画面、留白或反转。\n\n"
        "铁律：不新增材料里没有的事实；保留作者原声，他自己的用词优先于你的润色；"
        "改动要克制，只动该动的。输出完整修订稿，不要解释改了什么。\n\n"
    )


